/**
 * Scott & Burgan (2005) 40 standard fire behavior fuel models, RMRS-GTR-153.
 *
 * These are the fuel models LANDFIRE's FBFM40 layer encodes, so a raster cell's value
 * indexes directly into this table. Parameters are in the Imperial units the Rothermel
 * model is formulated in; conversion to metric happens at the display boundary only.
 *
 *   load      oven-dry fuel load, pounds per square foot (1 ton/acre = 0.04591 lb/ft²)
 *   savRatio  surface-area-to-volume ratio, square feet per cubic foot (ft²/ft³ = 1/ft)
 *   depth     fuel bed depth, feet
 *   extinction moisture, fraction of oven-dry weight
 */

export interface FuelLoad {
  dead1h: number;
  dead10h: number;
  dead100h: number;
  liveHerb: number;
  liveWoody: number;
}

export interface FuelModel {
  code: number;
  name: string;
  description: string;
  depthFeet: number;
  /** Dead fuel moisture of extinction, as a fraction (0.15 = 15 percent). */
  deadMoistureOfExtinction: number;
  load: FuelLoad;
  savDead1hPerFoot: number;
  savLiveHerbPerFoot: number;
  savLiveWoodyPerFoot: number;
  /**
   * Dynamic models move part of the live herbaceous load into a dead herbaceous class as
   * herbaceous moisture falls, which is what makes cured grass carry fire.
   */
  dynamic: boolean;
}

