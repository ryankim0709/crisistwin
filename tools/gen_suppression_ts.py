"""Generate app/src/studio/suppressionData.generated.ts from tools/suppression_resources.json.

The Studio's suppression model (docs/adr/0048-suppression-engine.md) reads its resource numbers
from this generated module, never from hand-typed constants. Only the leaves the simulator uses
are emitted (by path prefix below), each with its unit and its provenance: `source` + `page`,
or `assumption: true` + `reason`. app/src/studio/suppressionData.test.ts fails when the two
files drift apart.

    python3 -m tools.gen_suppression_ts          # rewrite the TS module
    python3 -m tools.gen_suppression_ts --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from tools.suppression_data import iter_leaves, load_resources

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "src" / "studio" / "suppressionData.generated.ts"

# Leaf path prefixes the simulator reads. A prefix ending in "." takes the whole section.
