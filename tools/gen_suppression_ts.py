def _selected(path: str) -> bool:
    for prefix in PREFIXES:
        if prefix.endswith("."):
            if path.startswith(prefix):
                return True
        elif path == prefix or path.startswith(prefix + "."):
            return True
    return False


def selected_leaves(data: dict) -> dict:
    out: dict[str, dict] = {}
    for path, leaf in iter_leaves(data):
        if not _selected(path):
            continue
        entry = {"value": leaf["value"], "unit": leaf["unit"]}
        if leaf.get("assumption"):
            entry["assumption"] = True
            entry["reason"] = leaf["reason"]
        else:
            entry["source"] = leaf["source_id"]
            entry["page"] = leaf["page"]
        out[path] = entry
    return out


def render(data: dict) -> str:
    leaves = selected_leaves(data)
    used = sorted({leaf["source"] for leaf in leaves.values() if "source" in leaf})
    sources = {}
    for sid in used:
        src = data["sources"][sid]
        sources[sid] = {"title": src["title"], "url": src["url"]}
        if src.get("verified") is False:
            sources[sid]["verified"] = False
    body = json.dumps(
        {"generated": data["meta"]["generated"], "sources": sources, "leaves": leaves},
        indent=2,
        ensure_ascii=False,
    )
    return (
        "// GENERATED by tools/gen_suppression_ts.py from tools/suppression_resources.json. Do not edit.\n"
        "// Regenerate: python3 -m tools.gen_suppression_ts. Sync test: suppressionData.test.ts.\n\n"
        "export interface SuppressionLeaf {\n"
        "  value: unknown;\n"
        "  unit: string;\n"
        "  source?: string;\n"
        "  page?: string;\n"
        "  assumption?: true;\n"
        "  reason?: string;\n"
        "}\n\n"
        "export interface SuppressionDataModule {\n"
        "  generated: string;\n"
        "  sources: Record<string, { title: string; url: string; verified?: false }>;\n"
        "  leaves: Record<string, SuppressionLeaf>;\n"
        "}\n\n"
        f"export const SUPPRESSION_DATA: SuppressionDataModule = {body};\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    data = load_resources()
    text = render(data)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date; run python3 -m tools.gen_suppression_ts", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(selected_leaves(data))} leaves)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
