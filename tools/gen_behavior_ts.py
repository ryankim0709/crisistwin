"""Generate app/src/population/behaviorParams.generated.ts from sim/behavior_params.json.

Simulation Studio draws per-household evacuation behaviour (population/householdBehavior.ts) from
the `grounded` profile of sim/behavior_params.json (docs/people-data.md "Behaviour evidence").
Only the parameters the Studio uses are emitted, each with its label and the evidence entries
(locator and source ids) behind it, so the numbers are never hand-typed in TypeScript.

    python3 -m tools.gen_behavior_ts          # rewrite the TS module
    python3 -m tools.gen_behavior_ts --check  # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "sim" / "behavior_params.json"
OUT = ROOT / "app" / "src" / "population" / "behaviorParams.generated.ts"

PROFILE = "grounded"
# Parameters of the profile the Studio reads (or documents as not modelled).
PARAMS = ("order_compliance", "shadow_evacuation", "wait_and_see_given_compliance", "departure_delay")


def build() -> str:
    data = json.loads(SOURCE.read_text())
    profile = data["profiles"][PROFILE]["params"]
    evidence = data["evidence"]
    params = {}
    for name in PARAMS:
        param = dict(profile[name])
        param["evidence"] = [
            {
                "id": key,
                "locator": evidence.get(key, {}).get("locator"),
                "sources": evidence.get(key, {}).get("sources", []),
                "label": evidence.get(key, {}).get("label"),
            }
            for key in profile[name].get("evidence", [])
        ]
        params[name] = param
    module = {
        "source": "sim/behavior_params.json",
        "schema": data["schema"],
        "retrieved": data["retrieved"],
        "profile": PROFILE,
        "params": params,
    }
    body = json.dumps(module, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by tools/gen_behavior_ts.py from sim/behavior_params.json. Do not edit.\n"
        "// Regenerate: python3 -m tools.gen_behavior_ts.\n\n"
        "export interface BehaviorEvidenceRef {\n"
        "  id: string;\n"
        "  locator: string | null;\n"
        "  sources: string[];\n"
        "  label: string | null;\n"
        "}\n\n"
        "export interface BehaviorParam {\n"
        "  kind: string;\n"
        "  label: string;\n"
        "  p?: number;\n"
        "  median_min?: number;\n"
        "  sigma?: number;\n"
        "  max_min?: number;\n"
        "  note?: string;\n"
        "  evidence: BehaviorEvidenceRef[];\n"
        "}\n\n"
        "export const BEHAVIOR_PARAMS: {\n"
        "  source: string;\n"
        "  schema: string;\n"
        "  retrieved: string;\n"
        "  profile: string;\n"
        f"  params: Record<{' | '.join(json.dumps(name) for name in PARAMS)}, BehaviorParam>;\n"
        f"}} = {body};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run python3 -m tools.gen_behavior_ts", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
